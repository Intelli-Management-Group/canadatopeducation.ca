<ul>
<li>纳奈莫最早作为殖民贸易站点成立于19世纪 早期。1849年,当时的哈得逊湾公司通过原住民获悉这里有大量的煤矿资源。公司在市中 心建立一座碉堡Bastion并开始了采矿经营。 直到今天这座碉堡被完整的保存了下来，并且成为了这座城市的历史象征。</li>
<li>从19世纪末到20世纪早期，纳奈莫作为一个重要的煤矿资源产出地而迅速发展。采矿业和筑路业的崛起吸引了当时大量华人涌向这 个城市,使纳奈莫一度成为卑诗省第二大华人聚集地，并且成立了一座中国城China Town, 辛亥革命先驱孙中山先生曾到访此处为之后的幸 亥革命筹集捐款。至今纳奈莫保存了许多具有中国特色的地标建筑,比如, China Steps, Nanaimo's Third Chinatown 和Chinese Memorial Gardens Park等。</li>
</ul>
